CREATE OR REPLACE FUNCTION public.link_existing_user()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
BEGIN
  -- wrap everything in exception so NOTHING can block signup
  BEGIN
    UPDATE existing_users_data
    SET auth_id = NEW.id
    WHERE "Email" = NEW.email AND auth_id IS NULL;
  EXCEPTION WHEN OTHERS THEN NULL;
  END;

  BEGIN
    INSERT INTO profiles (id, full_name, created_at)
    SELECT
      NEW.id,
      COALESCE(e."Fname" || ' ' || e."Lname", NEW.email),
      NOW()
    FROM existing_users_data e
    WHERE e."Email" = NEW.email
    ON CONFLICT (id) DO UPDATE
    SET full_name = EXCLUDED.full_name;
  EXCEPTION WHEN OTHERS THEN NULL;
  END;

  BEGIN
    INSERT INTO subscriptions (user_id, status, plan, started_at, expires_at)
    SELECT
      NEW.id,
      CASE WHEN e."payStatus" = '1' THEN 'active' ELSE 'inactive' END,
      'default',
      NOW(),
      NOW() + INTERVAL '1 year'
    FROM existing_users_data e
    WHERE e."Email" = NEW.email
    ON CONFLICT (user_id) DO UPDATE
    SET status = EXCLUDED.status;
  EXCEPTION WHEN OTHERS THEN NULL;
  END;

  RETURN NEW; -- always return NEW no matter what
END;
$function$
;

CREATE OR REPLACE FUNCTION public.handle_new_user()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
    declare
      new_code text;
      referrer_id uuid;
      incoming_ref text;
    begin
      select string_agg(
        substr('0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ', (random() * 36)::int + 1, 1),
        ''
      )
      into new_code
      from generate_series(1, 6);

      incoming_ref := new.raw_user_meta_data->>'referral_code';

      if incoming_ref is not null and trim(incoming_ref) != '' then
        select id into referrer_id
        from public.profiles
        where referral_code = trim(incoming_ref);
      end if;

      -- Leave referrer_id as NULL if none provided (awaiting official coordinator details)

      insert into public.profiles (
        id, email, full_name, referral_code, referred_by, role, created_at,
        affiliate_balance, slot_bonus, referral_earnings, total_referrals
      )
      values (
        new.id,
        new.email,
        coalesce(nullif(trim(new.raw_user_meta_data->>'full_name'), ''), new.email, 'AgroHeal Member'),
        new_code,
        referrer_id,
        'member',
        now(),
        0, 0, 0, 0
      )
      on conflict (id) do update set
        email = coalesce(excluded.email, public.profiles.email),
        full_name = case when public.profiles.full_name is null or public.profiles.full_name = '' then excluded.full_name else public.profiles.full_name end;

      return new;
    end;
    $function$
