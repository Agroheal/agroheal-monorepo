CREATE OR REPLACE FUNCTION public.prevent_role_self_escalation()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
    BEGIN
      -- Allow default 'member' role on INSERT
      IF TG_OP = 'INSERT' AND (NEW.role = 'member' OR NEW.role IS NULL) THEN
        NEW.role := 'member';
        RETURN NEW;
      END IF;

      IF NEW.role IS DISTINCT FROM COALESCE(OLD.role, 'member') THEN
        IF auth.role() = 'service_role' OR auth.role() = 'postgres' THEN
          RETURN NEW;
        END IF;
        IF is_admin(auth.uid()) THEN
          RETURN NEW;
        END IF;
        RAISE EXCEPTION 'Not authorized to change role';
      END IF;
      RETURN NEW;
    END;
    $function$
;

