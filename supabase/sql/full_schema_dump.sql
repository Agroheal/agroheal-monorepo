CREATE OR REPLACE FUNCTION public.subscribe_with_wallet_balance(p_user_id uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
    DECLARE
      v_current_earnings NUMERIC;
      v_already_subscribed BOOLEAN;
      v_sub_id UUID;
    BEGIN
      -- Check current earnings
      SELECT COALESCE(referral_earnings, 0) INTO v_current_earnings
      FROM public.profiles
      WHERE id = p_user_id;

      IF v_current_earnings IS NULL THEN
        RETURN jsonb_build_object('success', false, 'message', 'Profile not found.');
      END IF;

      IF v_current_earnings < 10000 THEN
        RETURN jsonb_build_object(
          'success', false, 
          'message', 'Insufficient wallet balance. Minimum ₦10,000 required to activate project subscription from wallet.'
        );
      END IF;

      -- Check if already subscribed
      SELECT EXISTS (
        SELECT 1 FROM public.subscriptions 
        WHERE user_id = p_user_id AND status = 'active' AND (expires_at IS NULL OR expires_at > NOW())
      ) INTO v_already_subscribed;

      IF v_already_subscribed THEN
        RETURN jsonb_build_object('success', false, 'message', 'User already has an active project subscription.');
      END IF;

      -- Deduct ₦10,000 from referral earnings and wallet balance
      UPDATE public.profiles
      SET 
        referral_earnings = referral_earnings - 10000,
        wallet_balance = GREATEST(0, COALESCE(wallet_balance, 0) - 10000)
      WHERE id = p_user_id;

      -- Record transaction in wallet_ledger
      INSERT INTO public.wallet_ledger (
        user_id, amount, balance_after, category, status, reference_id, description, entry_type
      ) VALUES (
        p_user_id,
        -10000,
        v_current_earnings - 10000,
        'SUBSCRIPTION',
        'AVAILABLE',
        'WAL-SUB-' || substr(md5(random()::text), 1, 10),
        'Project subscription activated using ₦10,000 wallet credit',
        'DEBIT'
      );

      -- Activate lifetime Green Card subscription (100 years)
      INSERT INTO public.subscriptions (
        user_id, plan, status, started_at, expires_at, slots
      ) VALUES (
        p_user_id,
        'green_card',
        'active',
        NOW(),
        NOW() + INTERVAL '100 years',
        1
      )
      RETURNING id INTO v_sub_id;

      RETURN jsonb_build_object(
        'success', true, 
        'message', 'Project subscription successfully activated using wallet balance!',
        'subscription_id', v_sub_id,
        'remaining_earnings', v_current_earnings - 10000
      );
    END;
    $function$
;

CREATE OR REPLACE FUNCTION public.pay_checkout_with_wallet(p_user_id uuid, p_checkout_id uuid, p_amount numeric, p_slots integer, p_slot_price numeric, p_category text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
    DECLARE
      v_current_balance NUMERIC;
      v_ref TEXT;
      v_sub_id UUID;
    BEGIN
      -- Check current earnings/balance
      SELECT COALESCE(referral_earnings, 0) INTO v_current_balance
      FROM public.profiles
      WHERE id = p_user_id;

      IF v_current_balance IS NULL THEN
        RETURN jsonb_build_object('success', false, 'message', 'User profile not found.');
      END IF;

      IF v_current_balance < p_amount THEN
        RETURN jsonb_build_object(
          'success', false, 
          'message', 'Insufficient wallet balance. You have ₦' || v_current_balance || ' but order requires ₦' || p_amount || '.'
        );
      END IF;

      -- Generate reference
      v_ref := 'WAL-PAY-' || substr(md5(random()::text), 1, 10);

      -- Deduct from wallet balance and referral earnings
      UPDATE public.profiles
      SET 
        referral_earnings = referral_earnings - p_amount,
        wallet_balance = GREATEST(0, COALESCE(wallet_balance, 0) - p_amount)
      WHERE id = p_user_id;

      -- Update checkout record
      UPDATE public.checkout
      SET 
        status = 'paid',
        payment_method = 'wallet',
        transaction_ref = v_ref
      WHERE id = p_checkout_id AND user_id = p_user_id;

      -- Record double-entry debit in wallet_ledger
      INSERT INTO public.wallet_ledger (
        user_id, amount, balance_after, category, status, reference_id, description, entry_type
      ) VALUES (
        p_user_id,
        -p_amount,
        v_current_balance - p_amount,
        'SLOT_PURCHASE',
        'AVAILABLE',
        v_ref,
        'Reinvestment: ' || p_slots || ' farm slot(s) purchased via wallet balance',
        'DEBIT'
      );

      -- Create active slot subscription
      INSERT INTO public.slot_subscriptions (
        user_id,
        checkout_id,
        amount,
        slotprice,
        status,
        slots,
        last_payment_date,
        next_payment_date,
        project_category
      ) VALUES (
        p_user_id,
        p_checkout_id,
        p_amount,
        p_slot_price,
        'active',
        p_slots,
        NOW(),
        NOW() + INTERVAL '30 days',
        p_category
      ) RETURNING id INTO v_sub_id;

      RETURN jsonb_build_object(
        'success', true,
        'message', 'Payment successful! ' || p_slots || ' farm slot(s) activated from your wallet balance.',
        'transaction_ref', v_ref,
        'remaining_balance', v_current_balance - p_amount,
        'subscription_id', v_sub_id
      );
    END;
    $function$
;

